def _unpack_obfuscated_wrappers(blob: bytes, key: bytes):
    raw = bytes(b ^ key[i % len(key)] for i, b in enumerate(blob)).decode("utf-8")
    return [tuple(chunk.split("\x1f")) for chunk in raw.split("\x1e")]

SYMBOLIC_WRAPPERS = _unpack_obfuscated_wrappers(_OBFUSCATED_SYMBOLIC_BLOB, _OBFUSCATED_KEY)
_LEGACY_NULL_WRAPPERS = _unpack_obfuscated_wrappers(_OBFUSCATED_LEGACY_BLOB, _OBFUSCATED_KEY)
_ALL_WRAPPERS = SYMBOLIC_WRAPPERS + _LEGACY_NULL_WRAPPERS

_DEOBFUSCATE_REGEX = re.compile(
    r'(?:' + '|'.join(f'{re.escape(pre)}([0-9a-fA-F]{{2}}){re.escape(post)}' for pre, post in _ALL_WRAPPERS) + r')'
)

# --- Symbolic Obfuscated Cipher Utilities ---
def _generate_random_noise(min_len: int = 2, max_len: int = 6) -> str:
    """
    Genera ruido aleatorio con caracteres alfabéticos limpios,
    sin utilizar separadores ($%&#) ni letras 'n, u, l, N, U, L'.
    """
    safe_noise = "abcdefghjkmopqrstwxyzABCDEFGHJKMOPQRSTWXYZ"
    length = random.randint(min_len, max_len)
    return ''.join(random.choice(safe_noise) for _ in range(length))

def _obfuscate_byte_hex_chunks(hex_str: str) -> str:
    """
    Toma una cadena hexadecimal de bytes (2 caracteres hex por byte).
    Envuelve cada byte seleccionando entre las 64 combinaciones de envoltorios simbólicos y numéricos.
    """
    chunks = [hex_str[i:i+2] for i in range(0, len(hex_str), 2)]
    obfuscated_parts = []
    connectors = ["=", "_", "-", "~", "+", ""]
    num_wrappers = len(SYMBOLIC_WRAPPERS)
    
    for chunk in chunks:
        pre_noise = _generate_random_noise(2, 5)
        post_noise = _generate_random_noise(2, 5)
        pre_wrap, post_wrap = SYMBOLIC_WRAPPERS[random.randint(0, num_wrappers - 1)]
        wrapped = f"{pre_wrap}{chunk}{post_wrap}"
        connector = random.choice(connectors)
        obfuscated_parts.append(f"{pre_noise}{connector}{wrapped}{connector}{post_noise}")
        
    return "".join(obfuscated_parts)

def _deobfuscate_byte_hex(obfuscated_str: str) -> str:
    """Extrae todos los bytes de 2 caracteres hex contenidos en cualquiera de los envoltorios."""
    return "".join(next(g for g in m.groups() if g is not None) for m in _DEOBFUSCATE_REGEX.finditer(obfuscated_str))

# --- Public API for Text Encryption ---
def encrypt_text(text: str, delimiter: str = DEFAULT_SEPARATOR) -> str:
    """
    Encrypts a string into a self-contained Null-Obfuscated Cipher bundle.
    Contains both the ephemeral key and encrypted payload in the same text,
    disguised with NULL wrappers and joined by the delimiter ($, %, &, #, ?).
    """
    if not text:
        return ""
    if delimiter not in SEPARATORS:
        delimiter = DEFAULT_SEPARATOR
        
    # 1. Generate unique 256-bit key for this message
    key_bytes = os.urandom(32)
    key_hex = key_bytes.hex()
    
    # 2. Encrypt text using stream cipher (generates 16-byte nonce + XOR data)
    data_bytes = text.encode('utf-8')
    payload_bytes = _encrypt(data_bytes, key_bytes)
    payload_hex = payload_bytes.hex()
    
    # 3. Disguise both Key and Payload with NULL variations
    obf_key = _obfuscate_byte_hex_chunks(key_hex)
    obf_payload = _obfuscate_byte_hex_chunks(payload_hex)
    
    # 4. Join with delimiter
    return f"{obf_key}{delimiter}{obf_payload}"

def decrypt_text(encrypted_input: str) -> str:
    """
    Decrypts an encrypted string.
    Automatically detects if it is a Null-Obfuscated Cipher bundle
    (delimited by $, %, &, #, ?) or falls back to legacy Base64 format.
    """
    if not encrypted_input:
        return ""
    
    stripped = encrypted_input.strip()
    
    # Check for Null-Obfuscated bundle separators
    found_sep = None
    for sep in SEPARATORS:
        if sep in stripped:
            found_sep = sep
            break
            
    if found_sep:
        # --- Null-Obfuscated Cipher Decryption ---
        parts = stripped.split(found_sep, 1)
        if len(parts) != 2:
            raise ValueError("Formato inválido: el texto cifrado no contiene las dos partes separadas.")
            
        obf_key, obf_payload = parts
        
        # 1. Recover Key
        key_hex = _deobfuscate_byte_hex(obf_key)
        if len(key_hex) != 64:
            raise ValueError(f"Clave corrupta o incompleta: se esperaban 64 dígitos hex, se obtuvieron {len(key_hex)}.")
        key_bytes = bytes.fromhex(key_hex)
        
        # 2. Recover Payload (Nonce + Ciphertext)
        payload_hex = _deobfuscate_byte_hex(obf_payload)
        if len(payload_hex) < 32:
            raise ValueError("Mensaje cifrado corrupto o demasiado corto.")
            
        payload_bytes = bytes.fromhex(payload_hex)
        
        # 3. Decrypt with recovered key
        decrypted_bytes = _decrypt(payload_bytes, key_bytes)
        return decrypted_bytes.decode('utf-8')
    else:
        # --- Legacy Base64 Fallback ---
        try:
            encrypted_bytes = base64.urlsafe_b64decode(stripped)
            decrypted_bytes = _decrypt(encrypted_bytes, CLAVE)
            return decrypted_bytes.decode('utf-8')
        except (ValueError, base64.binascii.Error) as e:
            raise ValueError("Texto cifrado inválido: no contiene un separador válido ni coincide con el formato Base64 legado.") from e

# --- Base64 Generic Functions ---
def base64_encode(text: str) -> str:
    """Encodes a string to Base64."""
    if not text:
        return ""
    return base64.b64encode(text.encode('utf-8')).decode('utf-8')

def base64_decode(b64_text: str) -> str:
    """Decodes a Base64 string."""
    if not b64_text:
        return ""
    try:
        return base64.b64decode(b64_text).decode('utf-8')
    except Exception as e:
        raise ValueError(f"Invalid Base64 string: {e}")

# --- Public API for File Encryption ---
def encrypt_file(file_path: str) -> bytes:
    """Encrypts a file's content and returns the encrypted data as bytes."""
    file_size = os.path.getsize(file_path)
    if file_size > 500 * 1024 * 1024:  # 500 MB limit
        raise ValueError("File is too large to encrypt (limit: 500MB).")

    try:
        with open(file_path, "rb") as infile:
            file_data = infile.read()
        return _encrypt(file_data, CLAVE)
    except IOError as e:
        raise IOError(f"Error reading file for encryption: {e}") from e

def decrypt_file(encrypted_file_path: str) -> bytes:
    """Decrypts a file's content and returns the decrypted data as bytes."""
    if not encrypted_file_path.endswith(".enc"):
        print("Warning: Selected file for decryption does not end with .enc")

    try:
        with open(encrypted_file_path, "rb") as infile:
            encrypted_data = infile.read()
        return _decrypt(encrypted_data, CLAVE)
    except (IOError, ValueError) as e:
        raise ValueError(f"Could not decrypt. Key might be incorrect or file is corrupt. Error: {e}") from e
